export const MATH_SYMBOLS = ['π', '∑', '∞', '√', 'Δ', 'Ω', 'φ', 'λ', 'θ', '±'];

export function getConstantById(id: string): MathConstant | undefined {
  return MATH_CONSTANTS.find(c => c.id === id);
}

export function getRandomConstants(count: number): MathConstant[] {
  const shuffled = [...MATH_CONSTANTS].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

export function getConstantsByCategory(category: string): MathConstant[] {
  return MATH_CONSTANTS.filter(c => c.category === category);
}
